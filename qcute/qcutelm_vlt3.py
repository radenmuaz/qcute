"""qcute.qcutelm_vlt3 — fork of qcute.qcutelm_vlt2 collapsing the separate
PoolerEncoder/UnpoolerDecoder (two distinct weight sets) into a SINGLE
shared-weight tiny causal transformer that plays both roles, like a normal
byte-level LM with a discrete bottleneck spliced into the middle of its
sequence.

Design (as specified in conversation):
  - "Encoder" stage: feed bytes[0..T-1] through the shared causal blocks,
    with a trainable "code-query" token appended at the end (position T).
    This stage also gets an auxiliary next-token-prediction (NTP) loss on
    the byte positions themselves (standard causal LM loss) — free extra
    gradient signal into the shared weights beyond just the bottleneck
    path, the same role bytelm.py's loss plays, but here shared with the
    tokenizer's own weights instead of a separate model.
  - The code-query position's final hidden state is projected + BSQ-
    quantized -> z_hat (same bsq_quantize as every other module in this
    repo).
  - "Decode" stage: z_hat is projected to a single embedding that becomes
    a *variable* BOS token (content-dependent, not a fixed learned
    vector) — z_proj(z_hat) at position 0, followed by teacher-forced
    byte embeddings chunk[0..T-2] at positions 1..T-1. Run through the
    SAME shared blocks (same weights as the encoder stage) with a causal
    mask, predicting chunk[0..T-1].

Two sequential forward calls through one shared Block stack, not two
separate encoder/decoder module instances — "single model AR, like a tiny
LM" per the design brief. This is mathematically identical to running one
concatenated sequence [bytes, code_query, code_bos, decode_bytes] through
a single attention call with a block mask that (a) lets the code-query
position attend back over the byte region (pooling) and (b) fully blocks
the decode region from attending to the byte/code-query region (so the
bottleneck is enforced structurally, not just by convention) — implemented
here as two plain causal calls instead of one masked call, since the
decode stage's first token (the code embedding) isn't known until the
*entire* encoder stage (all layers) has finished, so the two stages are
inherently sequential regardless of masking; splitting them into two calls
avoids a fragile custom-mask implementation for an equivalent result.

Con (flagged in the design brief, not fixed here): reconstruction decode
is genuinely autoregressive at inference time (unlike qcutelm_vlt2's
one-shot broadcast/prefix decode) — must be generated byte-by-byte, one
step per position. Acceptable because T <= K is small (<=4 in this repo's
configs so far). Training itself is NOT autoregressive-slow: the decode
stage is a single parallel forward pass via teacher forcing (like normal
LM training), so only 2 sequential forward passes are needed per training
step, not T.

No shared imports with qcutelm_vlt/qcutelm_vlt2 (self-contained-module
convention) — Logger/Checkpointer/data-loading/schedule helpers duplicated
verbatim.
"""
